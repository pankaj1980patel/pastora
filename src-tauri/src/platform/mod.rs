//! OS-specific code: native macOS, and a cross-platform version for Windows and Linux.

#[derive(Debug, Default)]
pub struct Snapshot {
    pub types: Vec<String>,
    pub text: Option<String>,
    pub files: Vec<String>,
    pub has_image: bool,
}

/// Marker type added to everything Pastora writes, so the watcher can skip it.
pub const INTERNAL_TYPE: &str = "com.pastora.internal";

/// Pasteboard types that password managers use to say "do not record this".
pub const CONCEALED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    // Windows: set by password managers to keep the item out of clipboard tools.
    "ExcludeClipboardContentFromMonitorProcessing",
];

#[cfg(target_os = "macos")]
mod macos;
#[cfg(target_os = "macos")]
pub use macos::*;

#[cfg(not(target_os = "macos"))]
mod generic;
#[cfg(not(target_os = "macos"))]
pub use generic::*;
